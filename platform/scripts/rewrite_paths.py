"""Rewrite Markdown links and path mentions for the course-first layout (private, build only).

    uv run python platform/scripts/rewrite_paths.py --before <commit> [--check] [FILE ...]

`--before` is the last commit in the old layout. For every Markdown file of the course (public
and private, except VERIFICATION.md, instructor/engineering-notes/, TeamTrack's own documents,
and the kit and skill templates that describe a learner's repository), the script:

- resolves each relative link and image against the file's old location; when the target was a
  tracked file or folder in the old layout, the link is rewritten to the target's new location,
  relative to the file's new location (anchors and queries are kept);
- rewrites path mentions in backticks (`scripts/lint_prose.py`, `submodules/01-instructions/`,
  `src/shipharness/ab/referee.py:40-60`), in plain text, and in fenced commands that name a
  tracked old path from the repository root (with a slash; bare words such as `skills` or
  `datasets` are also command names) and do not also name a file next to the document; command
  path arguments (`--app teamtrack`, `skills validate skills`) move too.

`--check` rewrites nothing and exits 1 when a file would change. Without FILE arguments every
course Markdown file is processed.

    uv run python platform/scripts/rewrite_paths.py --links [FILE ...]

checks that every relative link and image in the course Markdown files resolves (exit 1 if not).
"""

from __future__ import annotations

import argparse
import posixpath
import re
import subprocess
from pathlib import Path

REPO = next(p for p in Path(__file__).resolve().parents if (p / "pyproject.toml").is_file())

# Old prefix -> new prefix, most specific first. Folder prefixes end with "/".
_SECTIONS = ("01-instructions", "02-state-lifecycle", "03-scope-sandbox", "04-verification")
MAPPING: tuple[tuple[str, str], ...] = (
    *((f"submodules/{s}/solution/", f"{s}/assignment/solution/") for s in _SECTIONS),
    *((f"submodules/{s}/", f"{s}/") for s in _SECTIONS),
    ("src/", "platform/src/"),
    ("teamtrack/", "platform/teamtrack/"),
    ("sandbox/", "platform/sandbox/"),
    ("config/", "platform/config/"),
    ("datasets/", "platform/datasets/"),
    ("tests/", "platform/tests/"),
    ("scripts/", "platform/scripts/"),
    ("kit/", "use-in-your-repo/kit/"),
    ("skills/", "use-in-your-repo/skills/"),
    ("docs/apply-to-your-repo.md", "use-in-your-repo/apply-to-your-repo.md"),
    ("docs/setup-windows.md", "setup/windows.md"),
    ("docs/setup-macos.md", "setup/macos.md"),
    ("docs/setup-linux.md", "setup/linux.md"),
    ("setup/PRE-CLASS.md", "setup/pre-class.md"),
    ("CHANGELOG.md", "docs/CHANGELOG.md"),
    ("REFERENCES.md", "docs/REFERENCES.md"),  # generated by the release build
)
GENERATED = ("REFERENCES.md",)
SKIP_PREFIXES = (
    "VERIFICATION.md",
    "instructor/engineering-notes/",
    "platform/teamtrack/",  # TeamTrack's documents describe the app tree (frozen with it)
    "use-in-your-repo/kit/templates/",  # paths in a learner's repository
    "use-in-your-repo/kit/examples/boltons-queueutils/filled/",
    "use-in-your-repo/skills/harness-setup/assets/templates/",
    ".venv/",
)

_LINK = re.compile(r"(!?\[)([^\]\n]*)(\]\()(<?)([^)\s>]+)(>?)((?:\s+\"[^\"]*\")?\))")
# A fence opener or closer: three or more backticks (no backtick after them) or tildes.
_FENCE = re.compile(r"^ {0,3}(?:`{3,}[^`]*|~{3,}.*)$")
_REFDEF = re.compile(r"^(\s{0,3}\[[^\]\n]+\]:\s+)(<?)(\S+?)(>?)(\s.*)?$")
_SPAN = re.compile(r"`([^`\n]+)`")
_PATH = re.compile(r"(?<![\w./-])((?:\.\./|\./)*[A-Za-z][\w.-]*(?:/[\w.-]*)*/?)(:\d+(?:-\d+)?)?")


def map_path(old: str) -> str | None:
    """The new location of an old repository path (file or folder), or None if it did not move."""
    for before, after in MAPPING:
        if before.endswith("/"):
            if old == before.rstrip("/") or old.startswith(before):
                return after.rstrip("/") + old[len(before.rstrip("/")) :]
        elif old == before:
            return after
    return None


def old_location(new: str) -> str:
    """The old path of a file at `new` (the inverse of `map_path`)."""
    for before, after in sorted(MAPPING, key=lambda m: -len(m[1])):
        if after.endswith("/"):
            if new.startswith(after):
                return before + new[len(after) :]
        elif new == after:
            return before
    return new


class OldTree:
    def __init__(self, files: list[str]) -> None:
        self.files = set(files) | set(GENERATED)
        self.dirs = {posixpath.dirname(f) for f in files}
        for d in list(self.dirs):
            while d:
                d = posixpath.dirname(d)
                self.dirs.add(d)
        self.dirs.discard("")

    def exists(self, path: str) -> bool:
        path = path.rstrip("/")
        return path in self.files or path in self.dirs


def tracked(ref: str) -> list[str]:
    out = subprocess.run(
        ["git", "ls-tree", "-r", "-z", "--name-only", "--full-tree", ref],
        cwd=REPO,
        capture_output=True,
        check=True,
    ).stdout.decode("utf-8")
    return [p for p in out.split("\0") if p]


def _relative(target: str, from_dir: str, original: str) -> str:
    rel = posixpath.relpath(target, from_dir or ".")
    if original.endswith("/") and not rel.endswith("/"):
        rel += "/"
    if rel in (".", "./"):
        rel = "./"
    elif original.startswith("./") and not rel.startswith("../"):
        rel = "./" + rel
    return rel


def rewrite_link(target: str, old_file: str, new_file: str, tree: OldTree) -> str:
    if re.match(r"^[a-z][a-z0-9+.-]*:", target) or target.startswith(("#", "/")):
        return target
    match = re.match(r"([^#?]*)(.*)", target)
    assert match is not None
    path, suffix = match.groups()
    if not path:
        return target
    old_target = posixpath.normpath(posixpath.join(posixpath.dirname(old_file), path))
    if old_target.startswith("../") or not tree.exists(old_target):
        return target
    new_target = map_path(old_target) or old_target
    new_dir = posixpath.dirname(new_file)
    new_rel = _relative(new_target, new_dir, path)
    as_written = posixpath.normpath(posixpath.join(new_dir, path))
    if as_written == posixpath.normpath(posixpath.join(new_dir, new_rel)):
        return target  # already right (for example a link inside a folder that moved as one)
    return new_rel + suffix


BARE_FILES = ("CHANGELOG.md", "REFERENCES.md")  # root files named without a folder
# Path arguments of course commands that name a moved folder without a slash.
_COMMAND_ARG = re.compile(
    r"(?P<lead>(?:--(?:app|root|repo|build|product)[ =]|assess\.py |\bcd )|skills validate )"
    r"(?P<name>teamtrack|skills)\b(?![/\w.-])"
)


def rewrite_command_args(text: str) -> str:
    """`--app teamtrack`, `assess.py teamtrack`, `cd teamtrack`, `skills validate skills`."""

    def one(m: re.Match[str]) -> str:
        name = m.group("name")
        if name == "skills" and not m.group("lead").startswith("skills validate"):
            return m.group(0)
        if name == "teamtrack" and m.group("lead").startswith("skills validate"):
            return m.group(0)
        return m.group("lead") + (map_path(name) or name)

    return _COMMAND_ARG.sub(one, text)


def rewrite_mention(token: str, old_file: str, tree: OldTree) -> str:
    """A path from the repository root in its new place. A bare word (no slash) is left alone:
    `skills`, `datasets`, `tests`, and `sandbox` are also command, option, and prose words."""
    if token.startswith(("./", "../")):
        return token
    if token.endswith(".") and len(token) > 1:  # the end of a sentence
        return rewrite_mention(token[:-1], old_file, tree) + "."
    if "/" not in token and token not in BARE_FILES:
        return token
    clean = token.rstrip("/")
    here = posixpath.normpath(posixpath.join(posixpath.dirname(old_file), clean))
    if posixpath.dirname(old_file) and tree.exists(here):
        return token  # a path next to the document (a skill's scripts/, a section's starter/)
    if not tree.exists(clean) or map_path(clean) is None:
        return token
    new = map_path(clean)
    assert new is not None
    return new + ("/" if token.endswith("/") and not new.endswith("/") else "")


def rewrite_span(span: str, old_file: str, tree: OldTree) -> str:
    def one(m: re.Match[str]) -> str:
        return rewrite_mention(m.group(1), old_file, tree) + (m.group(2) or "")

    return rewrite_command_args(_PATH.sub(one, span))


def rewrite_link_text(text: str, old_file: str, tree: OldTree) -> str:
    """A link text that is itself a repository path ([skills/](...)) names the new path."""
    match = _PATH.fullmatch(text)
    if not match:
        return text
    return rewrite_mention(match.group(1), old_file, tree) + (match.group(2) or "")


def rewrite_text(text: str, old_file: str, new_file: str, tree: OldTree) -> str:
    out: list[str] = []
    fence = False
    for line in text.splitlines(keepends=True):
        if _FENCE.match(line.rstrip("\n")):
            fence = not fence
            out.append(line)
            continue
        if fence:
            out.append(_rewrite_code_line(line, old_file, tree))
            continue
        line = _LINK.sub(
            lambda m: (
                m.group(1)
                + rewrite_link_text(m.group(2), old_file, tree)
                + m.group(3)
                + m.group(4)
                + rewrite_link(m.group(5), old_file, new_file, tree)
                + m.group(6)
                + m.group(7)
            ),
            line,
        )
        ref = _REFDEF.match(line.rstrip("\n"))
        if ref:
            new_target = rewrite_link(ref.group(3), old_file, new_file, tree)
            line = line.replace(ref.group(3), new_target, 1)
        line = _SPAN.sub(lambda m: "`" + rewrite_span(m.group(1), old_file, tree) + "`", line)
        out.append(rewrite_prose(line, old_file, tree))
    return "".join(out)


def rewrite_prose(line: str, old_file: str, tree: OldTree) -> str:
    """Plain-text path mentions (`Source: teamtrack/docs/HANDBOOK.md`, a span broken over two
    lines, a folder tree): the same rule as in backticks, outside code spans and link targets."""
    parts = re.split(r"(`[^`\n]*`|\]\([^)\n]*\))", line)
    for i in range(0, len(parts), 2):
        parts[i] = _PATH.sub(
            lambda m: rewrite_mention(m.group(1), old_file, tree) + (m.group(2) or ""), parts[i]
        )
    return "".join(parts)


def _rewrite_code_line(line: str, old_file: str, tree: OldTree) -> str:
    """Commands in fenced blocks: `uv run python scripts/x.py`, `cd teamtrack`, paths after make
    variables (A2_IMPL=submodules/...)."""
    moved = re.sub(
        r"(?:^|(?<=[\s=\"'(]))((?:submodules|src|teamtrack|sandbox|config|datasets|tests|scripts|kit"
        r"|skills|docs|setup)/[\w./-]*)",
        lambda m: rewrite_mention(m.group(1), old_file, tree),
        line,
    )
    return rewrite_command_args(moved)


def _markdown_files() -> list[str]:
    out = subprocess.run(
        ["git", "ls-files", "-z", "--", "*.md"], cwd=REPO, capture_output=True, check=True
    ).stdout.decode("utf-8")
    return sorted(p for p in out.split("\0") if p)


def course_files() -> list[str]:
    """The Markdown files the rewrite touches."""
    return [p for p in _markdown_files() if not p.startswith(SKIP_PREFIXES)]


# Markdown whose relative links resolve in another tree, not in this repository: templates copied
# into a learner's repository, and instruction trees overlaid on TeamTrack in an arm workspace
# (the A1 checker resolves those against the overlay).
OTHER_TREE = (
    "use-in-your-repo/kit/templates/",
    "use-in-your-repo/kit/examples/boltons-queueutils/filled/",
    "use-in-your-repo/skills/harness-setup/assets/templates/",
    "01-instructions/assignment/starter/instructions/",
    "01-instructions/assignment/solution/work/instructions/",
    "platform/teamtrack/harness/instructions/",
)


def link_files() -> list[str]:
    """The Markdown files the link check reads: every tracked one except the lead's verification
    record, the engineering notes, and the files whose links resolve in another tree."""
    skip = (*SKIP_PREFIXES[:2], *OTHER_TREE)
    return [p for p in _markdown_files() if not p.startswith(skip)]


def broken_links(files: list[str]) -> list[str]:
    """Every relative link or image in `files` whose target does not exist in the working tree
    (the generated docs/REFERENCES.md counts as present)."""
    generated = {map_path(g) for g in GENERATED}
    problems: list[str] = []
    for rel in files:
        fence = False
        for number, line in enumerate((REPO / rel).read_text(encoding="utf-8").splitlines(), 1):
            if _FENCE.match(line):
                fence = not fence
                continue
            if fence:
                continue
            line = _SPAN.sub("``", line)  # links inside code spans are examples, not links
            for match in _LINK.finditer(line):
                target = match.group(5)
                if re.match(r"^[a-z][a-z0-9+.-]*:", target) or target.startswith(("#", "/")):
                    continue
                path = re.split(r"[#?]", target, maxsplit=1)[0]
                if not path:
                    continue
                resolved = posixpath.normpath(posixpath.join(posixpath.dirname(rel), path))
                if resolved in generated or (REPO / resolved).exists():
                    continue
                problems.append(f"{rel}:{number}: {target}")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--before", help="the last commit in the old layout")
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--links", action="store_true", help="only check that every relative link resolves"
    )
    parser.add_argument("files", nargs="*")
    args = parser.parse_args(argv)
    if args.links:
        problems = broken_links(args.files or link_files())
        for problem in problems:
            print(f"x {problem}")
        print(f"{len(problems)} broken relative link(s)")
        return 1 if problems else 0
    if not args.before:
        parser.error("--before is required unless --links is given")
    tree = OldTree(tracked(args.before))
    changed = []
    for new_file in args.files or course_files():
        path = REPO / new_file
        text = path.read_text(encoding="utf-8")
        new_text = rewrite_text(text, old_location(new_file), new_file, tree)
        if new_text != text:
            changed.append(new_file)
            if not args.check:
                path.write_text(new_text, encoding="utf-8", newline="\n")
    for name in changed:
        print(("would rewrite " if args.check else "rewrote ") + name)
    print(f"{len(changed)} file(s) {'to rewrite' if args.check else 'rewritten'}")
    return 1 if args.check and changed else 0


if __name__ == "__main__":
    raise SystemExit(main())
